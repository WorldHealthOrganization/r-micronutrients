      "ferritin_unadj_mean_sd",
      "ferritin_unadj_mean_ll",
      "ferritin_unadj_mean_ul",
      "ferritin_unadj_25percentile",
      "ferritin_unadj_50percentile",
      "ferritin_unadj_75percentile",
      "depletedironstores_unadj_r",
